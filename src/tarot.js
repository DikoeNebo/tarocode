window.tarotPreset = (id) =>
  window.TAROT_PRESETS.find((p) => p.id === id) || window.TAROT_PRESETS[0];

window.tarotImageUrl = (id) => {
  const p = window.tarotPreset(id);
  return `app://tarot/${p.file}`;
};

window.getTarotPickerValue = (container) =>
  container?.dataset?.value || window.TAROT_PRESETS[0].id;

window.fillTarotImagePicker = (container, selectedId) => {
  if (!container) return;
  const groups = [...new Set(window.TAROT_PRESETS.map((p) => p.group))];
  const pick = selectedId || window.TAROT_PRESETS[0].id;

  container.innerHTML = groups
    .map((group) => {
      const items = window.TAROT_PRESETS.filter((p) => p.group === group);
      return `<section class="tarot-picker-group">
        <h4 class="tarot-picker-group-title">${group}</h4>
        <div class="tarot-picker-grid">${items
          .map(
            (p) =>
              `<button type="button" class="tarot-picker-item${
                p.id === pick ? " selected" : ""
              }" data-id="${p.id}" aria-pressed="${p.id === pick}">
                <img src="${window.tarotImageUrl(p.id)}" alt="" loading="lazy" />
                <span class="tarot-picker-name">${p.name}</span>
              </button>`
          )
          .join("")}</div>
      </section>`;
    })
    .join("");

  container.dataset.value = pick;

  container.querySelectorAll(".tarot-picker-item").forEach((btn) => {
    btn.addEventListener("click", () => {
      container.querySelectorAll(".tarot-picker-item").forEach((b) => {
        b.classList.remove("selected");
        b.setAttribute("aria-pressed", "false");
      });
      btn.classList.add("selected");
      btn.setAttribute("aria-pressed", "true");
      container.dataset.value = btn.dataset.id;
    });
  });
};
